def sh(cmd, root):
    try: return subprocess.run(cmd, shell=True, cwd=root, capture_output=True, text=True, timeout=120).stdout
    except Exception: return ""

def walk(root, exts):
    for d, dirs, fs in os.walk(root):
        dirs[:] = [x for x in dirs if x not in SKIP and not x.startswith(".")]
        for f in fs:
            if f.endswith(exts): yield os.path.relpath(os.path.join(d, f), root).replace(os.sep, "/")

def classify(path, text):
    if TEST_RE.search(path): return "test", "test"
    for rx, kind, layer in KIND_RULES:
        if re.search(rx, path) or (rx.startswith("(@") and re.search(rx, text)): return kind, layer
    return "other", "unknown"

def humanize(name):
    name = name.replace("+", " + ")
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", name).lower()

def auto_summary(text, kind, name, platform):
    line = ""
    first = P[platform]["symbol"].search(text)
    if first:
        above = text[:first.start()].rstrip("\n").split("\n")
        doc = []
        for ln in reversed(above):
            st = ln.strip()
            if st.startswith("///") or st.startswith("*") or st.startswith("/**") or st.startswith("*/") or st.startswith("@"):
                if st.startswith("@"): continue
                doc.append(st.lstrip("/* ").strip())
            else: break
        doc = [d for d in reversed(doc) if d and not d.startswith("Copyright")]
        if doc: line = doc[0]
    if 10 <= len(line) <= 160: return "AUTO: " + line
    return f"AUTO: {kind} `{name}` ({humanize(name)}); no doc comment"

def hash_text(t): return hashlib.sha1(t.encode("utf-8", "ignore")).hexdigest()[:12]

def read_prose(path):
    if not os.path.exists(path): return None
    t = open(path, encoding="utf-8").read()
    i = t.find(GEN_END)
    return t[i + len(GEN_END):].lstrip("\n") if i >= 0 else t  # a file without markers is treated as all prose

def load_template(names, name):
    for d in names:
        p = os.path.join(d, name)
        if os.path.exists(p):
            t = open(p, encoding="utf-8").read()
            return re.sub(r"^<!--.*?-->\s*", "", t, count=1, flags=re.S)
    return ""

def write_view(path, generated, prose_template):
    prose = read_prose(path)
    if prose is None: prose = prose_template
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(GEN_START + "\n" + generated.rstrip("\n") + "\n" + GEN_END + "\n\n" + prose.rstrip("\n") + "\n")

def first_prose_line(path, heading):
    prose = read_prose(path)
    if not prose: return ""
    m = re.search(r"^##\s+" + re.escape(heading) + r"[^\n]*\n(.*?)(?=^##\s|\Z)", prose, re.S | re.M)
    if not m: return ""
    for line in m.group(1).splitlines():
        s = line.strip().lstrip("- ").strip()
        if s and not s.startswith("{{"): return s
    return ""

def slug(s): return re.sub(r"[^A-Za-z0-9]+", "__", s).strip("_") or "root"

def md_cell(s): return str(s).replace("|", "\\|").replace("\n", " ")

def load_codeowners(root):
    for p in ("CODEOWNERS", ".github/CODEOWNERS", "docs/CODEOWNERS"):
        fp = os.path.join(root, p)
        if os.path.exists(fp):
            rules = []
            for line in open(fp, encoding="utf-8", errors="ignore"):
                line = line.strip()
                if not line or line.startswith("#"): continue
                parts = line.split()
                rules.append((parts[0].lstrip("/"), " ".join(parts[1:])))
            return rules
    return []

def owner_of(path, rules):
    best = ""
    for pat, owner in rules:
        if fnmatch.fnmatch(path, pat) or fnmatch.fnmatch(path, pat.rstrip("/") + "/*") or path.startswith(pat.rstrip("/") + "/"): best = owner
    return best

def split_top(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<(": depth += 1
        elif ch in ">)": depth -= 1
        if ch == "," and depth == 0: out.append(cur); cur = ""
        else: cur += ch
    out.append(cur)
    return [re.sub(r"\(.*", "", x).strip().split(".")[-1].split("<")[0] for x in out if x.strip()]

